// Rebuild components/learn/learn.css from the original .astro components.
//
//   node scripts/extract-learn-css.mjs
//
// The five components 1062 content files depend on carry their appearance in
// <style> blocks. Copying those out unchanged means a page that renders wrong
// is a porting bug rather than a restyle, which is the only way to review a
// change this wide.
//
// <script> blocks are stripped FIRST. DataCampExercise builds a fullscreen
// document inside a JavaScript string, and that string contains the text
// "<style>" -- a naive match swallowed the surrounding JS into the stylesheet
// and PostCSS then failed on it.
import { readFileSync, writeFileSync } from "node:fs";

const SOURCES = {
  Figure: "src/components/Figure.astro",
  FileCode: "src/components/FileCode.astro",
  Quiz: "src/components/Quiz.astro",
  DataCampExercise: "src/components/DataCampExercise.astro",
  AlgorithmCard: "src/components/AlgorithmCard.astro",
  MathDrillDeck: "src/components/MathDrillDeck.astro",
  YoutuberCard: "src/components/YoutuberCard.astro",
  BuyMeCoffee: "src/components/BuyMeCoffee.astro",
  Contact: "src/components/Contact.astro",
  CompanyBoard: "src/components/dsa/CompanyBoard.astro",
  SheetTracker: "src/components/dsa/SheetTracker.astro",
  CrossSheetMap: "src/components/dsa/CrossSheetMap.astro",
  PhaseMap: "src/components/dsa/PhaseMap.astro",
  StudyPlanner: "src/components/dsa/StudyPlanner.astro",
  DrillDeck: "src/components/dsa/DrillDeck.astro",
  MockInterview: "src/components/dsa/MockInterview.astro",
};

const HEADER = `/* =========================================================================
   Learning components — styles carried over from the Astro build.

   GENERATED by scripts/extract-learn-css.mjs. Edit the source components, or
   replace this file wholesale in phase 2; do not hand-patch it.

   These are the five components 1062 of the 1190 content files import, so
   their appearance is load-bearing for the content cutover. The rules are the
   originals, moved out of each .astro file's <style> block unchanged, so a
   page that renders wrong is a porting bug and not a restyle.
   ========================================================================= */

/* ---- Starlight compatibility shim --------------------------------------
   A handful of Starlight variables survive in the rules below. Mapping them
   to the new tokens keeps the extracted CSS identical to the original, which
   is what makes it reviewable. Phase 2 deletes this block with the last
   reference to it. */
:root {
  --sl-color-bg-nav: color-mix(in srgb, var(--color-surface) 55%, transparent);
  --sl-color-gray-2: var(--foreground);
  --sl-color-gray-3: var(--muted);
  --sl-color-white: var(--foreground);
  --sl-color-text: var(--foreground);

  /* The extracted rules also use the old brand token names. */
  --pch-line: var(--line);
  --pch-ink: var(--color-ink);
  --pch-surface: var(--color-surface);
  --pch-blue: var(--color-python-blue);
  --pch-blue-bright: var(--color-python-blue-bright);
  --pch-amber: var(--color-python-amber);
  --pch-amber-deep: var(--color-python-amber-deep);
  --pch-string: var(--color-token-string);
  --pch-comment: var(--color-token-comment);
}
`;

let out = HEADER;

for (const [name, path] of Object.entries(SOURCES)) {
  const src = readFileSync(path, "utf8");

  // Remove script blocks before looking for styles — see the note above.
  const withoutScripts = src.replace(/<script[\s\S]*?<\/script>/g, "");
  const blocks = [...withoutScripts.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]);

  if (!blocks.length) {
    console.log(`${name.padEnd(20)} no style block`);
    continue;
  }

  let css = blocks.join("\n").replace(/^\n+|\n+$/g, "");

  /**
   * `:global(X)` is Astro's escape hatch from component-scoped styles. Outside
   * Astro it is not a real selector and PostCSS rejects it — which is exactly
   * how the first production build failed. These rules are already global
   * here, so unwrapping is exact rather than an approximation.
   */
  css = css.replace(/:global\(([^)]*)\)/g, "$1");

  // A JS fragment that slipped through would show up as a stray operator; the
  // stylesheet is the wrong place to discover that at request time.
  if (/^\s*['"].*\+\s*$/m.test(css)) {
    console.error(`${name}: extracted CSS still contains JavaScript — check the source.`);
    process.exit(1);
  }

  console.log(`${name.padEnd(20)} ${css.split("\n").length} lines`);
  out += `\n/* ---- ${name} ${"-".repeat(Math.max(0, 62 - name.length))} */\n${css}\n`;
}

writeFileSync("components/learn/learn.css", out);
console.log(`\ncomponents/learn/learn.css: ${out.split("\n").length} lines`);
