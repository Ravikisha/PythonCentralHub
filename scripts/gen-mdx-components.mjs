// Generate mdx-components.tsx from migration/mdx-component-list.json.
//
//   node scripts/gen-mdx-components.mjs
//
// The list is a committed file, not a scan of the content, because the scan's
// own input is what scripts/migrate-imports.mjs deletes: running this after the
// codemod found zero components and silently emptied the map. The codemod
// unions what it strips into the list, so the order of the two no longer
// matters.
//
// Generated rather than hand-maintained because it is ~40 entries whose only
// job is to mirror that list, and a missed entry shows up as "undefined is not
// a component" on a content page rather than as an error here.
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const COMPONENTS = "src/components";
const LIST = "migration/mdx-component-list.json";

const {
  ported,
  visualisations,
  aliases = {},
  starlightPrimitives = [],
  asides = [],
} = JSON.parse(
  readFileSync(LIST, "utf8")
);

function walk(dir, test, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) walk(p, test, out);
    else if (test(entry)) out.push(p);
  }
  return out;
}

/** name -> repo path, extension stripped (TS rejects .tsx in import paths). */
const tsxPath = new Map();
for (const f of walk(COMPONENTS, (f) => /\.tsx$/.test(f))) {
  const name = f.split(/[\\/]/).pop().replace(/\.tsx$/, "");
  if (!tsxPath.has(name)) tsxPath.set(name, f.split("\\").join("/").replace(/\.tsx$/, ""));
}

const missing = visualisations.filter((n) => !tsxPath.has(n));
if (missing.length) {
  console.error(`No .tsx found for: ${missing.join(", ")}`);
  process.exit(1);
}

const viz = [...visualisations].sort();

const body = `import type { MDXComponents } from "mdx/types";
${ported.map((n) => `import { ${n} } from "@/components/learn/${n}";`).join("\n")}
${
  starlightPrimitives.length
    ? `import { ${starlightPrimitives.join(", ")} } from "@/components/learn/StarlightPrimitives";`
    : ""
}
${asides.length ? `import { ${asides.join(", ")} } from "@/components/learn/Aside";` : ""}

/* Visualisation components, lazily loaded -- see components/learn/lazy-viz.tsx. */
import {
${viz.map((n) => `  ${n},`).join("\n")}
} from "@/components/learn/lazy-viz";

/**
 * Components available to every MDX page, without the page importing them.
 *
 * GENERATED by scripts/gen-mdx-components.mjs from
 * migration/mdx-component-list.json. Add a component there, not here.
 *
 * The Astro build required each page to import what it used, which is why
 * 1062 of the 1190 content files opened with an import line and a run of
 * \`../\`. Supplying them here let the migration delete those lines instead of
 * rewriting a thousand relative paths -- and an author adding a quiz to a new
 * page no longer counts directories.
 *
 * Five components carried almost all of that coupling: DataCampExercise (792
 * files), Quiz (595), Figure (292), FileCode (203), ProblemLadder (118).
 */
export function getMDXComponents(components?: MDXComponents): MDXComponents {
  return {
${[...ported, ...starlightPrimitives, ...asides, ...viz].map((n) => `    ${n},`).join("\n")}
${Object.entries(aliases)
  .map(
    ([tag, impl]) =>
      `    /* content uses <${tag}> for ${impl} */\n    ${tag}: ${impl},`
  )
  .join("\n")}
    ...components,
  };
}

export default getMDXComponents;
`;

writeFileSync("mdx-components.tsx", body);

/*
 * The visualisations go through a client module of next/dynamic wrappers.
 * Imported straight into mdx-components (a server module), every one of them
 * landed in the lesson route's client bundle -- a 477 KB chunk, framer-motion
 * included, on every lesson, although most lessons use none. Next only splits
 * a client component lazily when the dynamic() call is itself in a client
 * module (docs: guides/lazy-loading), hence this file. Each wrapper still
 * renders on the server, so the markup is unchanged; only the page that uses
 * a visualisation downloads its code.
 */
const lazy = `"use client";

/*
 * GENERATED by scripts/gen-mdx-components.mjs. Do not edit by hand.
 *
 * One next/dynamic wrapper per visualisation, so a lesson downloads only the
 * visualisations it renders. See the note in the generator for why this has
 * to be a client module.
 */
import dynamic from "next/dynamic";

${viz.map((n) => `export const ${n} = dynamic(() => import("@/${tsxPath.get(n)}"));`).join("\n")}
`;
writeFileSync("components/learn/lazy-viz.tsx", lazy);
console.log(`mdx-components.tsx: ${ported.length} ported + ${viz.length} visualisation component(s)`);
